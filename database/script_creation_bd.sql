CREATE TABLE Collaborator(
    id INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    login VARCHAR(50) NOT NULL,
    firstName VARCHAR(50) NOT NULL,
    lastName VARCHAR(50) NOT NULL
);

CREATE TABLE Task(
    id INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    description VARCHAR(255) NOT NULL,
    echeance DATE NOT NULL,
    idState INTEGER NOT NULL REFERENCES TASKSTATE(id) ON DELETE CASCADE,
    creator INTEGER NOT NULL REFERENCES COLLABORATOR(id),
    startTime DATE NULL,
    currentWorker INTEGER REFERENCES COLLABORATOR(id) ON DELETE SET NULL
);

CREATE TABLE ElapsedTimeOnTask(
    idTask INTEGER REFERENCES Task(id) ON DELETE CASCADE,
    idCollaborator INTEGER REFERENCES Collaborator(id) ON DELETE SET NULL,
    elapsedTime INTEGER DEFAULT 0 NOT NULL,
    PRIMARY KEY (idTask, idCollaborator)
);


